import { Player, LIFE, FURY } from './player.js';
import { Enemy } from './enemy.js';
import { input } from './input.js';
import { Particles } from './particles.js';
import { Scene, WORLD_WIDTH } from './scene.js';
import { Pickup, PICKUP, FloatingText } from './pickups.js';

const canvas = document.getElementById('game');
const ctx = canvas.getContext('2d');
const stateEl = document.getElementById('state');

// UNIT: screen pixels per design pixel (the size of the characters on
// screen). The sheets are drawn `detail` times finer, so they are drawn at
// UNIT / detail: same size, more detail.
const UNIT = 4;
let debug = false;
let shake = 0; // screen shake strength (px), fades out

function resize() {
  canvas.width = innerWidth;
  canvas.height = innerHeight;
  ctx.imageSmoothingEnabled = false;
}
addEventListener('resize', resize);
resize();

// (onload instead of img.decode(): decode() can hang while the page is
// in the background)
function loadImage(src) {
  return new Promise((resolve, reject) => {
    const img = new Image();
    img.onload = () => resolve(img);
    img.onerror = () => reject(new Error(`não carregou ${src}`));
    img.src = src;
  });
}

// Painted art wins: if public/assets/<name>-art.png exists (see
// docs/arte/ESPECIFICACAO.md) it's used with <name>-art.json; otherwise the
// sheet generated by tools/make-*.mjs.
const loadPair = (file) => Promise.all([
  loadImage(`/assets/${file}.png`),
  fetch(`/assets/${file}.json`).then((r) => r.json()),
]);
const loadSheet = (name) => loadPair(`${name}-art`).catch(() => loadPair(name));
const [[sheet, meta], [saxonSheet, saxonMeta]] = await Promise.all([loadSheet('viking'), loadSheet('saxon')]);

const scene = new Scene(UNIT);
const START = { x: 300, enemyX: 900 }; // world px
let camX = 0;      // left edge of the view in the world (px)
let placed = false; // actors put on the path on the first frame (the screen
                    // size isn't known yet while the page is still loading)
let player = makePlayer();
let saxon = makeSaxon(START.enemyX, innerHeight * 0.72);
let pickups = [];  // meat and runes lying on the ground
const texts = [];  // "+3", "FÚRIA!" floating up
let emberTime = 0; // when the next fury ember rises
let respawn = 0;   // s until the next Saxon walks in
let hitStop = 0;   // s the action freezes on a hit, so it feels heavy
let defeated = 0;  // s since the viking fell (0 = still fighting)
let score = 0;     // Saxons defeated
const dust = new Particles();
if (import.meta.env.DEV) { // handy in the console
  Object.defineProperty(window, 'camX', { get: () => camX, configurable: true });
  Object.defineProperty(window, 'player', { get: () => player, configurable: true });
  Object.defineProperty(window, 'saxon', { get: () => saxon, configurable: true });
}

function makePlayer() {
  const p = new Player(sheet, meta, UNIT / (meta.detail || 1), START.x, innerHeight * 0.75);
  p.onFootstep = onFootstep;
  p.onHit = onAxe;
  p.onLand = onLand;
  return p;
}

function makeSaxon(x, y) {
  const e = new Enemy(saxonSheet, saxonMeta, UNIT / (saxonMeta.detail || 1), x, y, 90);
  e.onAttack = onSpear;
  e.onDown = onSaxonDown;
  return e;
}

// start over: full life, a fresh Saxon
function restart() {
  player = makePlayer();
  saxon = makeSaxon(START.enemyX, innerHeight * 0.72);
  camX = 0;
  placed = false;
  pickups = [];
  texts.length = 0;
  defeated = 0;
  score = 0;
  respawn = 0;
}

// how far the axe reaches in front of the viking, and how far up/down
const AXE_REACH = { front: 32 * UNIT, depth: 12 * UNIT };

function onFootstep(p) {
  const run = p.anim === 'run';
  dust.burst(p.x - p.facing * 10, p.y, run ? 5 : 2, {
    vx: -p.facing * (run ? 60 : 20), spread: run ? 45 : 20, size: run ? 6 : 4,
  });
}

function onAxe(p) {
  shake = 7;
  dust.burst(p.x + p.facing * 22 * UNIT, p.y - 2, 9, { vx: p.facing * 90, spread: 100, size: 6 });

  // did the axe catch the Saxon? (in front, close enough, same depth)
  const ahead = (saxon.x - p.x) * p.facing;
  if (ahead > 0 && ahead < AXE_REACH.front && Math.abs(saxon.y - p.y) < AXE_REACH.depth && saxon.hit(p.x, p.damage)) {
    shake = p.furious ? 13 : 10;
    hitStop = p.furious ? 0.09 : 0.07;
    dust.burst(saxon.x, saxon.y - 18 * UNIT, 12, { vx: p.facing * 120, spread: 160, size: 5 });
    if (p.furious) dust.burst(saxon.x, saxon.y - 18 * UNIT, 10, { vx: p.facing * 160, spread: 200, size: 4, color: 'rgba(255,140,40,A)' });
    if (saxon.dead) score++;
  }
}

// the defeated Saxon hits the ground (and sometimes drops a meat)
function onSaxonDown(e) {
  shake = 5;
  dust.burst(e.x - e.facing * 8 * UNIT, e.y, 12, { vx: 0, spread: 180, size: 7 });
  if (Math.random() < PICKUP.dropChance) pickups.push(new Pickup('meat', e.x + e.facing * 6 * UNIT, e.y + 2 * UNIT, UNIT));
}

// meat and runes along the way: x as a fraction of the world, depth as a
// fraction of the walkable ground (0 = top, 1 = bottom)
const PLACES = [
  ['meat', 0.3, 0.3], ['rune', 0.47, 0.65], ['meat', 0.62, 0.7], ['meat', 0.8, 0.25], ['rune', 0.9, 0.5],
];
function placePickups(bounds) {
  pickups = PLACES.map(([kind, fx, fy]) =>
    new Pickup(kind, fx * WORLD_WIDTH, bounds.minY + fy * (bounds.maxY - bounds.minY), UNIT));
}

// the viking walked over something
function collect(item) {
  item.taken = true;
  const head = player.y - player.z - 52 * UNIT * 0.5;
  if (item.kind === 'meat') {
    const got = player.heal(PICKUP.meatLife);
    texts.push(new FloatingText(got ? `+${got}` : 'vida cheia', player.x, head, 'rgba(140,230,120,A)'));
    dust.burst(player.x, player.y - 14 * UNIT, 10, { spread: 70, size: 4, color: 'rgba(150,240,130,A)', rise: 60 });
  } else {
    player.startFury();
    shake = 6;
    texts.push(new FloatingText('FÚRIA!', player.x, head, 'rgba(255,150,50,A)'));
    dust.burst(player.x, player.y - 14 * UNIT, 18, { spread: 160, size: 5, color: 'rgba(255,120,40,A)', rise: 80 });
  }
}

function onLand(p) {
  dust.burst(p.x, p.y, 8, { vx: 0, spread: 140, size: 6 });
}

// the Saxon's thrust landed: did the spear reach the viking?
function onSpear(e) {
  if (e.reaches(player.x, player.y) && player.hurt(e.x)) {
    shake = 9;
    hitStop = 0.08;
    dust.burst(player.x, player.y - 16 * UNIT, 10, { vx: e.facing * 110, spread: 150, size: 5 });
  }
}

// the viking's life, top right (the help panel is on the left)
function drawPlayerLife() {
  const w = 220, h = 14, x = canvas.width - w - 24, y = 20;
  ctx.fillStyle = 'rgba(0,0,0,0.6)';
  ctx.fillRect(x - 3, y - 3, w + 6, h + 6);
  ctx.fillStyle = '#3a1410';
  ctx.fillRect(x, y, w, h);
  ctx.fillStyle = player.life > 2 ? '#d8402c' : '#ff6a3a';
  ctx.fillRect(x, y, Math.round((w * Math.max(0, player.life)) / LIFE.max), h);
  ctx.fillStyle = 'rgba(0,0,0,0.35)'; // marks for each hit
  for (let i = 1; i < LIFE.max; i++) ctx.fillRect(x + Math.round((w * i) / LIFE.max), y, 2, h);
  ctx.font = 'bold 12px system-ui, sans-serif';
  ctx.textAlign = 'right';
  ctx.fillStyle = '#f2e6d0';
  ctx.fillText(`VIKING · saxões derrotados: ${score}`, x + w, y + h + 18);

  // fury bar, draining, while it lasts
  if (player.furious) {
    const fy = y + h + 28, fh = 8;
    ctx.fillStyle = 'rgba(0,0,0,0.6)';
    ctx.fillRect(x - 3, fy - 3, w + 6, fh + 6);
    ctx.fillStyle = '#4a2008';
    ctx.fillRect(x, fy, w, fh);
    ctx.fillStyle = player.fury < 2 && Math.floor(player.fury * 6) % 2 ? '#ffd27a' : '#ff8a2a';
    ctx.fillRect(x, fy, Math.round((w * player.fury) / FURY.time), fh);
    ctx.fillStyle = '#ffb060';
    ctx.fillText('FÚRIA BERSERKER', x + w, fy + fh + 16);
  }
}

function drawDefeat() {
  const t = Math.min(1, defeated / 0.8); // fades in
  ctx.fillStyle = `rgba(10,6,6,${0.6 * t})`;
  ctx.fillRect(0, 0, canvas.width, canvas.height);
  if (t < 1) return;
  ctx.textAlign = 'center';
  ctx.fillStyle = '#f2e6d0';
  ctx.font = 'bold 42px system-ui, sans-serif';
  ctx.fillText('O viking caiu', canvas.width / 2, canvas.height / 2 - 10);
  ctx.font = '18px system-ui, sans-serif';
  ctx.fillText(`saxões derrotados: ${score} · aperte Enter para recomeçar`, canvas.width / 2, canvas.height / 2 + 28);
}

const groundTop = () => canvas.height * 0.55;

// the camera follows the viking smoothly, looking a bit ahead of where he
// faces, and never shows past the ends of the world
const CAMERA = { lookAhead: 0.12, follow: 5 };
function moveCamera(dt) {
  const W = canvas.width;
  const target = player.x - W / 2 + player.facing * W * CAMERA.lookAhead;
  camX += (target - camX) * Math.min(1, dt * CAMERA.follow);
  camX = Math.max(0, Math.min(Math.max(0, WORLD_WIDTH - W), camX));
}

function drawShadow(p) {
  const lift = Math.min(1, p.z / 120); // smaller and lighter while jumping
  ctx.fillStyle = `rgba(0,0,0,${0.3 - lift * 0.15})`;
  ctx.beginPath();
  ctx.ellipse(p.x, p.y, 11 * UNIT * (1 - lift * 0.4), 2.5 * UNIT * (1 - lift * 0.4), 0, 0, Math.PI * 2);
  ctx.fill();
}

// fury: a pulsing orange glow on the ground around the viking
function drawFuryGlow() {
  const fade = Math.min(1, player.fury / 2);
  const pulse = 0.5 + 0.5 * Math.sin(performance.now() / 120);
  const r = (16 + pulse * 3) * UNIT;
  ctx.save();
  ctx.translate(player.x, player.y);
  ctx.scale(1, 0.32);
  const g = ctx.createRadialGradient(0, 0, 0, 0, 0, r);
  g.addColorStop(0, `rgba(255,140,40,${(0.5 + pulse * 0.2) * fade})`);
  g.addColorStop(1, 'rgba(255,90,20,0)');
  ctx.fillStyle = g;
  ctx.fillRect(-r, -r, r * 2, r * 2);
  ctx.restore();
}

let last = performance.now();
function loop(now) {
  // clamp: the first timestamp can be earlier than `last`
  const dt = Math.max(0, Math.min(0.05, (now - last) / 1000));
  last = now;

  if (input.wasPressed('KeyB')) debug = !debug;

  const bounds = {
    minX: 60,
    maxX: WORLD_WIDTH - 60,
    minY: groundTop() + 40,
    maxY: canvas.height - 10,
  };
  // start both on the dirt path, in the middle of the walkable ground
  if (!placed && canvas.height > 0) {
    const pathY = bounds.minY + (bounds.maxY - bounds.minY) * 0.55;
    player.y = pathY;
    saxon.y = pathY - 8;
    placePickups(bounds);
    placed = true;
  }

  if (player.dead) {
    defeated += dt;
    if (defeated > 0.8 && input.wasPressed('Enter', 'NumpadEnter')) restart();
  }
  if (hitStop > 0) hitStop -= dt; // frozen for an instant on a hit
  else {
    player.update(dt, bounds);
    saxon.update(dt, player, bounds);
    dust.update(dt);
    moveCamera(dt);
    for (const item of pickups) {
      item.update(dt);
      if (item.touches(player) && !player.dead) collect(item);
    }
    pickups = pickups.filter((i) => !i.taken);
    for (const t of texts) t.update(dt);
    for (let i = texts.length - 1; i >= 0; i--) if (texts[i].done) texts.splice(i, 1);
    // fury: embers rise from the viking
    if (player.furious && (emberTime -= dt) <= 0) {
      emberTime = 0.035;
      dust.burst(player.x + (Math.random() - 0.5) * 16 * UNIT, player.y - player.z - Math.random() * 34 * UNIT, 1,
        { spread: 30, size: 5, color: 'rgba(255,120,30,A)', rise: 90 });
    }
  }

  // a defeated Saxon disappears; a new one walks in just outside the view,
  // ahead of the viking (or behind him, at the end of the world)
  if (saxon.gone) {
    respawn += dt;
    if (respawn > 1.2) {
      respawn = 0;
      const y = bounds.minY + Math.random() * (bounds.maxY - bounds.minY);
      const ahead = player.facing > 0 ? camX + canvas.width + 60 : camX - 60;
      const x = ahead > bounds.minX && ahead < bounds.maxX ? ahead
        : player.facing > 0 ? camX - 60 : camX + canvas.width + 60;
      saxon = makeSaxon(Math.max(bounds.minX, Math.min(bounds.maxX, x)), y);
    }
  }

  shake = Math.max(0, shake - dt * 40);
  ctx.save();
  if (shake) ctx.translate((Math.random() - 0.5) * shake, (Math.random() - 0.5) * shake);
  const cam = Math.round(camX);
  scene.draw(ctx, cam, groundTop());
  // the world moves with the camera; the life bar and texts stay on screen
  ctx.save();
  ctx.translate(-cam, 0);
  // whoever is lower on the screen is closer, so it's drawn last
  const actors = [player, ...(saxon.gone ? [] : [saxon])].sort((a, b) => a.y - b.y);
  actors.forEach(drawShadow);
  if (player.furious) drawFuryGlow();
  for (const item of pickups) item.draw(ctx);
  dust.draw(ctx, (p) => p.y < player.y);
  for (const a of actors) a.draw(ctx, debug);
  dust.draw(ctx, (p) => p.y >= player.y);
  if (!saxon.gone) saxon.drawLife(ctx);
  for (const t of texts) t.draw(ctx);
  ctx.restore();
  drawPlayerLife();
  if (player.dead) drawDefeat();
  ctx.restore();

  stateEl.textContent = `anim: ${player.anim}  quadro: ${player.frame + 1}  vel: ${player.speed | 0}`;

  input.endFrame();
  requestAnimationFrame(loop);
}
requestAnimationFrame(loop);
