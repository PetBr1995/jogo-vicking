// the camera follows the viking smoothly, looking a bit ahead of where he
// faces, and never shows past the ends of the world
const CAMERA = { lookAhead: 0.12, follow: 5 };
function moveCamera(dt) {
  const W = viewW;
  const target = player.x - W / 2 + player.facing * W * CAMERA.lookAhead;
  camX += (target - camX) * Math.min(1, dt * CAMERA.follow);
  camX = Math.max(0, Math.min(Math.max(0, worldW() - W), camX));
}

function drawShadow(p) {
  const lift = Math.min(1, p.z / 120); // smaller and lighter while jumping
  ctx.fillStyle = `rgba(0,0,0,${0.3 - lift * 0.15})`;
  ctx.beginPath();
  ctx.ellipse(p.x, p.y, 11 * CHAR_UNIT * (1 - lift * 0.4), 2.5 * CHAR_UNIT * (1 - lift * 0.4), 0, 0, Math.PI * 2);
  ctx.fill();
}

// a pulsing glow on the ground around the viking (fury, or a power being cast)
function drawGroundGlow(rgb, fade) {
  const pulse = 0.5 + 0.5 * Math.sin(performance.now() / 120);
  const r = (16 + pulse * 3) * UNIT;
  ctx.save();
  ctx.translate(player.x, player.y);
  ctx.scale(1, 0.32);
  const g = ctx.createRadialGradient(0, 0, 0, 0, 0, r);
  g.addColorStop(0, `rgba(${rgb},${(0.5 + pulse * 0.2) * fade})`);
  g.addColorStop(1, `rgba(${rgb},0)`);
  ctx.fillStyle = g;
  ctx.fillRect(-r, -r, r * 2, r * 2);
  ctx.restore();
}

// powers running over a body, drawn right on top of it: electricity or
// flames on the viking while he casts, flames on a burning Saxon
function drawBodyPower(a) {
  const t = performance.now() / 1000;
  if (a === player) {
    const level = player.auraLevel;
    if (!level) return;
    if (player.aura.kind === 'thunder') {
      if (!player.meta.anims.cast) drawBodyArcs(ctx, player.x, player.y - player.z, UNIT, level);
    } else {
      if (!player.meta.anims.castFire) drawBodyFlames(ctx, player.x, player.y - player.z, UNIT, level, player.facing, t);
    }
  } else if (a.burn > 0) {
    drawBodyFlames(ctx, a.x, a.y - a.z, UNIT, Math.min(1, a.burn / 0.5), a.facing, t + a.id);
  }
}

let last = performance.now();

function drawSimpleScreen(cam) {
  // Tela simples sem cenário (fundo sólido escuro e chão reto)
  ctx.fillStyle = '#141722';
  ctx.fillRect(0, 0, viewW, viewH);

  const gy = groundTop();
  ctx.fillStyle = '#1e2434';
  ctx.fillRect(0, gy, viewW, viewH - gy);

  // Linha sutil de base do piso
  ctx.fillStyle = '#313b54';
  ctx.fillRect(0, gy, viewW, 2);
}

function render() {
  ctx.save();
  if (shake && !paused) ctx.translate((Math.random() - 0.5) * shake, (Math.random() - 0.5) * shake);
  const cam = Math.round(camX);

  drawSimpleScreen(cam);

  // the world moves with the camera
  ctx.save();
  ctx.translate(-cam, 0);

  // Draw the Thunder Rune monolith on the floor
  if (runeMonolith) runeMonolith.draw(ctx, debug);

  // Actors sorted by Y so depth sorting is correct
  const actors = [player, ...saxons].sort((a, b) => a.y - b.y);
  for (const a of actors) {
    drawShadow(a);
    if (a === player && player.furious && !player.dead) drawGroundGlow('255,70,40', Math.min(1, player.fury / 2));
    if (a === player && player.electrified) drawGroundGlow('110,210,255', Math.max(player.auraLevel, 0.45));
    a.draw(ctx, debug);
    drawBodyPower(a);
  }
  for (const s of saxons) s.drawLife(ctx);

  dust.draw(ctx, (p) => p.y < player.y);
  dust.draw(ctx, (p) => p.y >= player.y);

  for (const b of bolts) b.draw(ctx);
  for (const st of strikes) st.draw(ctx);
  for (const imp of impacts) imp.draw(ctx);
  if (flyingAxe) flyingAxe.draw(ctx, sheet, meta, player.scale, player.furious);
  for (const t of texts) t.draw(ctx);
  ctx.restore();

  drawPlayerLife();

  if (flash > 0) {
    ctx.fillStyle = `rgba(220,240,255,${(flash / 0.1) * 0.35})`;
    ctx.fillRect(-20, -20, viewW + 40, viewH + 40);
  }
  if (paused) drawPause();
  ctx.restore();

  const thunderText = player.thunder > 0 ? `⚡ RAIO ×${player.thunder}` : 'sem cargas (toque na runa)';
  stateEl.textContent = `anim: ${player.anim}  quadro: ${player.frame + 1}  vel: ${player.speed | 0}  pulo(z): ${Math.round(player.z)}px  ${thunderText}${paused ? '  [PAUSADO]' : ''}`;
}

// stops the requestAnimationFrame loop completely while paused
function setPaused(val) {
  if (player.dead) val = false;
  if (val === paused) return;
  paused = val;
  if (paused) {
    if (rafId) { cancelAnimationFrame(rafId); rafId = 0; }
    input.endFrame();
    render();
  } else {
    input.endFrame();
    last = performance.now();
    if (!rafId) rafId = requestAnimationFrame(loop);
  }
}

addEventListener('keydown', (e) => {
  if (e.repeat) return;
  if ((e.code === 'KeyP' || e.code === 'Escape') && placed && !player.dead) {
    setPaused(!paused);
  }
});
canvas.addEventListener('pointerdown', () => {
  if (paused) setPaused(false);
});
addEventListener('blur', () => {
  if (placed && !player.dead) setPaused(true);
});
document.addEventListener('visibilitychange', () => {
  if (document.hidden && placed && !player.dead) setPaused(true);
});

function loop(now) {
  rafId = 0;
  if (paused) return;
  // clamp: the first timestamp can be earlier than `last`
  const dt = Math.max(0, Math.min(0.05, (now - last) / 1000));
  last = now;

  if (input.wasPressed('KeyB')) debug = !debug;

  // Atalhos de teclado (1, 2, 3) para selecionar as formas para testes
  if (input.wasPressed('Digit1', 'Numpad1')) selectForm('base');
  if (input.wasPressed('Digit2', 'Numpad2')) selectForm('fury');
  if (input.wasPressed('Digit3', 'Numpad3')) selectForm('thunder');

  const bounds = {
    minX: 60,
    maxX: WORLD_WIDTH - 60,
    minY: groundTop() + 40,
    maxY: viewH - 10,
  };
  if (stage) {
    // painted stage: only where the picture really has ground
    bounds.minX = 10;
    bounds.maxX = stage.width - 10;
    bounds.minY = stage.minY;
    bounds.maxY = stage.maxY;
    bounds.walkable = (x, y) => stage.walkable(x, y);
  }
  // start on the dirt path, in the middle of the walkable ground
  if (!placed && viewH > 0) {
    const pathY = bounds.minY + (bounds.maxY - bounds.minY) * 0.55;
    player.x = START.x;
    player.y = pathY;
    if (runeMonolith) {
      runeMonolith.x = 650;
      runeMonolith.y = pathY;
    }
    placeSaxons(bounds);
    placed = true;
  }

  if (player.dead) {
    defeated += dt;
    if (defeated > 0.8 && input.wasPressed('Enter', 'NumpadEnter')) restart();
  }
  if (hitStop > 0) hitStop -= dt; // frozen for an instant on a hit
  else {
    player.update(dt, bounds);
    if (player.lockedForm === 'thunder' && player.thunder < 3) player.thunder = 10; // Mantém cargas prontas durante teste do modo trovão
    for (const s of saxons) s.update(dt, player, bounds, saxons);
    if (runeMonolith) runeMonolith.update(dt, player);
    dust.update(dt);
    moveCamera(dt);

    for (const b of bolts) {
      b.update(dt);
      if (b.x < -100 || b.x > worldW() + 100) {
        b.dead = true;
      } else {
        const hit = saxons
          .filter((s) => b.hits(s))
          .sort((a, c) => Math.abs(a.x - b.x) - Math.abs(c.x - b.x))[0];
        if (hit) boltHits(b, hit);
      }
    }
    bolts = bolts.filter((b) => !b.dead);

    for (const st of strikes) st.update(dt);
    strikes = strikes.filter((st) => !st.done);

    for (const imp of impacts) imp.update(dt);
    impacts = impacts.filter((imp) => !imp.done);

    // powers on bodies throw off sparks and embers
    if ((player.electrified || player.auraLevel > 0) && Math.random() < dt * 45) {
      dust.burst(player.x + (Math.random() - 0.5) * 18 * UNIT, player.y - player.z - Math.random() * 46 * UNIT, 1,
        { spread: 160, size: 3, color: 'rgba(160,230,255,A)', rise: 25 });
    }
    for (const s of saxons) {
      if (s.burn > 0 && Math.random() < dt * 25) {
        dust.burst(s.x + (Math.random() - 0.5) * 14 * UNIT, s.y - Math.random() * 44 * UNIT, 1,
          { spread: 30, size: 5, color: 'rgba(255,120,30,A)', rise: 90 });
      }
    }
    if (flyingAxe) {
      if (flyingAxe.update(dt, player)) { // caught it
        player.axeAway = false;
        flyingAxe = null;
        shake = 2;
        dust.burst(player.x + player.facing * 10 * UNIT, player.y - 20 * UNIT, 6, { spread: 80, size: 3, color: 'rgba(255,200,120,A)' });
      } else {
        for (const s of saxons) if (flyingAxe.hits(s)) thrownAxeHits(flyingAxe, s);
      }
    }
    flash = Math.max(0, flash - dt);
    for (const t of texts) t.update(dt);
    for (let i = texts.length - 1; i >= 0; i--) if (texts[i].done) texts.splice(i, 1);
    // (the fury's embers are drawn with the rest of its fire, see fury-fx.js)

    // Gerenciamento do adversário para teste do acerto do raio
    saxons = saxons.filter((s) => !s.gone);
    const nearbyAlive = saxons.some((s) => s.alive);
    if (!nearbyAlive && !player.dead) {
      respawn += dt;
      if (respawn > 1.6) {
        respawn = 0;
        spawnWave(bounds);
      }
    } else {
      respawn = 0;
    }
  }

  shake = Math.max(0, shake - dt * 40);
  render();

  input.endFrame();
  if (!paused) rafId = requestAnimationFrame(loop);
}
rafId = requestAnimationFrame(loop);
